# Separate positions keep the flash clear of the heart and scarf.
SPARKLES = {
    "h-plume": ((39, 2), (33, 7)),
    "b-dawn": ((44, 26), (37, 35)),
    "c-cloud": ((10, 32), (35, 33)),
    "c-star": ((31, 22), (26, 36)),
}


def symbol(name, body):
    return f'<symbol id="{name}" viewBox="0 0 48 48">{body}</symbol>'


def row_runs(row, palette, left, y):
    out = []
    x = 0
    while x < len(row):
        pixel = row[x]
        end = x + 1
        while end < len(row) and row[end] == pixel:
            end += 1
        if pixel != ".":
            out.append(f'<rect x="{left+x}" y="{y}" width="{end-x}" height="1" fill="{palette[int(pixel,16)]}"/>')
        x = end
    return "".join(out)


def assets():
    parts = []
    for (slot, key), ((x, y), palette, rows) in RECIPES.items():
        # Two purchase-free alternatives recolor the primary material only.
        variants = (palette[0], "#C86752", "#745B9D")
        for frame, color in enumerate(variants):
            scheme = (color, *palette[1:])
            part = "".join(row_runs(row, scheme, x, y+i) for i, row in enumerate(rows))
            parts.append(symbol(f"c019-{slot}-{key}-{frame}", part))
    for key, positions in SPARKLES.items():
        for frame, (x, y) in enumerate(positions):
            part = (f'<rect x="{x-1}" y="{y}" width="3" height="1" fill="#F5C568"/>'
                    f'<rect x="{x}" y="{y-1}" width="1" height="3" fill="#FFF8D5"/>')
            parts.append(symbol(f"c019-glint-{key}-{frame}", part))
    sheet = '<svg xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges"><defs>'
    sheet += "".join(parts) + "</defs></svg>" + chr(10)
    return {Path("cards/assets/postal/item-tiers/sprites.svg"): sheet}
