class Pixels:
    def __init__(self): self.p = [['.']*16 for _ in range(16)]
    def dot(self,x,y,c):
        if not (0<=x<16 and 0<=y<16): raise ValueError((x,y))
        self.p[y][x]=c
    def rect(self,x,y,w,h,c):
        for yy in range(y,y+h):
            for xx in range(x,x+w): self.dot(xx,yy,c)
    def line(self,x1,y1,x2,y2,c):
        n=max(abs(x2-x1),abs(y2-y1))
        for i in range(n+1):
            t=i/n if n else 0
            self.dot(round(x1+(x2-x1)*t),round(y1+(y2-y1)*t),c)
    def oval(self,x,y,w,h,c):
        for yy in range(y,y+h):
            for xx in range(x,x+w):
                if ((xx-x-(w-1)/2)/(w/2))**2+((yy-y-(h-1)/2)/(h/2))**2<=1: self.dot(xx,yy,c)
    def poly(self,pts,c):
        for y in range(min(p[1] for p in pts),max(p[1] for p in pts)+1):
            for x in range(min(p[0] for p in pts),max(p[0] for p in pts)+1):
                inside=False
                for a,b in zip(pts,pts[1:]+pts[:1]):
                    if (a[1]>y)!=(b[1]>y) and x<(b[0]-a[0])*(y-a[1])/(b[1]-a[1])+a[0]: inside=not inside
                if inside: self.dot(x,y,c)
        for a,b in zip(pts,pts[1:]+pts[:1]): self.line(*a,*b,c)
    def eyes(self,x=5,y=7,gap=4):
        self.dot(x,y,'k');self.dot(x+gap,y,'k')
    def mirror(self): self.p=[r[::-1] for r in self.p]
    def finish(self):
        old=[r[:] for r in self.p]
        for y in range(16):
            for x in range(16):
                if old[y][x]!='.':
                    for dx,dy in ((-1,0),(1,0),(0,-1),(0,1)):
                        a,b=x+dx,y+dy
                        if 0<=a<16 and 0<=b<16 and old[b][a]=='.': self.p[b][a]='k'
        return [''.join(r) for r in self.p]

