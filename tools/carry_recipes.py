# the front layer out, a number keeps only front pixels from that column rightwards. "paint": strap colours inside "area"
# (x0, x1, y0, y1; default everywhere) take the colour most of their neighbours have.
ICON = {
    "letter": {"front": None, "paint": {"#367B70"}},
    "hourglass": {"front": None},
    "octopus": {"front": None},
    "goose": {"front": 34, "paint": {"#985C3D", "#367B70"}, "area": (25, 45, 22, 32)},
    "cake": {"front": 31},
}


def paint_over(drawn, colors, area=None):
    x0, x1, y0, y1 = area or (-99, 199, -99, 199)
    todo = {p for p, c in drawn.items() if c in colors and x0 <= p[0] < x1 and y0 <= p[1] < y1}
    while todo:
        done = {}
        for (x, y) in todo:
            near = [drawn[q] for q in ((x-1, y), (x+1, y), (x, y-1), (x, y+1), (x-1, y-1), (x+1, y+1), (x-1, y+1), (x+1, y-1))
                    if q in drawn and q not in todo and drawn[q] != INK]
            if near:
                done[(x, y)] = max(sorted(set(near)), key=near.count)
        if not done:
            break
        drawn.update(done)
        todo -= set(done)
    return drawn
VARIANTS = (None, "#C86752", "#745B9D")   # the same two star colours as the C-019 items
ALPHA = "0123456789abcdefghijklmnopqrstuvwxyz"


def pixels(layer, primary=None):
    (left, top), palette, rows = layer
    palette = (primary or palette[0], *palette[1:])
    return {(left+x, top+y): palette[ALPHA.index(ch)] for y, row in enumerate(rows) for x, ch in enumerate(row) if ch != "."}


def rects(drawn):
    out, rows = [], {}
    for (x, y), color in drawn.items():
        rows.setdefault(y, {})[x] = color
    for y in sorted(rows):
        xs = sorted(rows[y]); i = 0
        while i < len(xs):
            j = i
            while j + 1 < len(xs) and xs[j+1] == xs[j] + 1 and rows[y][xs[j+1]] == rows[y][xs[i]]:
                j += 1
            out.append(f'<rect x="{xs[i]}" y="{y}" width="{j-i+1}" height="1" fill="{rows[y][xs[i]]}"/>')
            i = j + 1
    return "".join(out)


def assets():
    parts = []
    for key, layers in RECIPES.items():
        for part in ("back", "front"):
            if not layers[part]:
                continue
            for v, color in enumerate(VARIANTS):
                parts.append(f'<symbol id="c023-carry-{key}-{part}-{v}" viewBox="0 0 48 48" overflow="visible">{rects(pixels(layers[part], color))}</symbol>')
        rule = ICON.get(key, {})
        front = pixels(layers["front"]) if layers["front"] else {}
        if "front" in rule:
            front = {} if rule["front"] is None else {p: c for p, c in front.items() if p[0] >= rule["front"]}
        both = {**(pixels(layers["back"]) if layers["back"] else {}), **front}
        if "paint" in rule:
            both = paint_over(both, rule["paint"], rule.get("area"))
        xs = [p[0] for p in both]; ys = [p[1] for p in both]
        side = max(max(xs)-min(xs), max(ys)-min(ys)) + 3
        left = (min(xs)+max(xs)+1-side)//2; top = (min(ys)+max(ys)+1-side)//2
        parts.append(f'<symbol id="c023-carry-{key}-icon" viewBox="{left} {top} {side} {side}">{rects(both)}</symbol>')
    for (slot, key), item in GEAR.items():
        for part in ("back", "front"):
            if not item[part]:
                continue
            suffix = "" if part == "front" else "-back"
            for v, color in enumerate(VARIANTS):
                parts.append(f'<symbol id="c023-{slot}-{key}{suffix}-{v}" viewBox="0 0 48 48" overflow="visible">{rects(pixels(item[part], color))}</symbol>')
        both = {**(pixels(item["back"]) if item["back"] else {}), **pixels(item["front"])}
        xs = [p[0] for p in both]; ys = [p[1] for p in both]
        side = max(max(xs)-min(xs), max(ys)-min(ys)) + 3
        left = (min(xs)+max(xs)+1-side)//2; top = (min(ys)+max(ys)+1-side)//2
        parts.append(f'<symbol id="c023-{slot}-{key}-icon" viewBox="{left} {top} {side} {side}">{rects(both)}</symbol>')
    sheet = '<svg xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges"><defs>' + "".join(parts) + "</defs></svg>\n"
    return {Path("cards/assets/postal/carry/sprites.svg"): sheet}
